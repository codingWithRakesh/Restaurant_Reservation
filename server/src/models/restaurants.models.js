import {Schema, model} from 'mongoose';

const restaurantSchema = new Schema({
    name: {
        type: String,
        required: true
    },
    address: {
        type: String,
        required: true
    },
    phone: {
        type: String,
        required: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    opening_Time: {
        type: String,
        required: true
    },
    closing_Time: {
        type: String,
        required: true
    },
    description: {
        type: String,
        required: true
    },
    image: {
        type: String,
        required: true
    }
}, {timestamps: true});

const Restaurant = model('Restaurant', restaurantSchema);

export default Restaurant;